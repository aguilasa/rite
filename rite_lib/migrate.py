"""`rite.py migrate` — adopt a legacy backlog in place.

`--from frontmatter`: cycles from before the JSON state (Rite up to 0.13) keep their state in the
frontmatter of each item and of the progress file. The migration moves it to `progress.json` and
`fixes.json`, leaves each item file with its `id` only, and changes nothing else in any file. It
checks its own work before writing a byte: the cycles read back from the JSON must equal the cycles
read from the frontmatter, item by item and field by field.

`--from graph`: progress files written before the dependency graph became a generated view keep a
hand-drawn mermaid block. The migration swaps that block for the generated region (rendered from each
task's `depends_on`) and keeps every other line. An edge the hand-drawn graph has and `depends_on`
lacks is reported, never added: the JSON is the source, and the operator decides.

`--from we2002`:

The legacy system kept state in three places (frontmatter, progress tables with emoji, dates in table
columns). Migration makes frontmatter the single source: it reads the tables, writes the state into
each item's frontmatter, replaces the tables with generated regions, and maps Portuguese vocabulary
to Rite's closed vocabulary. No file is renamed or moved; run it on a branch and review the diff.
"""

